# Generates hooks/inked.ts: the "inked" icon style, from game-icons.net
# (https://game-icons.net, CC BY 3.0, credits in CREDITS.md). Each icon keeps
# its 512x512 path; the mod tints it with the theme's colour at draw time.
# Usage: python3 -I tools/make-inked.py <game-icons folder> hooks/inked.ts
import json, pathlib, re, sys

SRC = pathlib.Path(sys.argv[1])
OUT = pathlib.Path(sys.argv[2])

ICONS = {
    'party': 'lorc/crossed-swords',
    'sword': 'lorc/broadsword',
    'map': 'lorc/treasure-map',
    'kingdom': 'delapouite/castle',
    'here': 'delapouite/position-marker',
    'fame': 'delapouite/laurels-trophy',
    'settings': 'lorc/cog',
    'lever': 'lorc/lever',
    'camp': 'lorc/campfire',
    'campfire': 'lorc/campfire',
    'crate': 'lorc/knapsack',
    'quests': 'lorc/scroll-unfurled',
    'scroll': 'lorc/tied-scroll',
    'graveyard': 'lorc/tombstone',
    'skull': 'lorc/skull-crossed-bones',
    'stamina': 'lorc/hourglass',
    'heart': 'skoll/hearts',
    'heartHalf': 'skoll/hearts',
    'heartEmpty': 'skoll/hearts',
    'context': 'delapouite/magic-potion',
    'mana': 'delapouite/magic-potion',
    'coin': 'delapouite/two-coins',
    'chest': 'skoll/open-treasure-chest',
    'waiting': 'lorc/ringing-bell',
    'd20': 'delapouite/dice-twenty-faces-twenty',
    'd20one': 'delapouite/dice-twenty-faces-one',
    'book': 'delapouite/spell-book',
    'dragon': 'lorc/dragon-head',
}

BACKGROUND = re.compile(r'^M0 0h512v512H0z$')

def paths(svg):
    found = re.findall(r'<path([^>]*)\sd="([^"]+)"', svg)
    return [d for attrs, d in found if not BACKGROUND.match(d.strip())]

data = {}
for stem in sorted(set(ICONS.values())):
    data[stem.split('/')[1]] = ' '.join(paths((SRC / f'{stem}.svg').read_text()))
names = {name: stem.split('/')[1] for name, stem in ICONS.items()}

ts = (
    "// Generated by tools/make-inked.py from game-icons.net (CC BY 3.0: Lorc,\n"
    "// Delapouite and Skoll; recoloured at draw time; see CREDITS.md). Do not edit by hand.\n\n"
    f"const PATHS: Record<string, string> = {json.dumps(data, indent=2)}\n\n"
    f"const NAMES = {json.dumps(names, indent=2)} as const\n\n"
    "export type InkedName = keyof typeof NAMES\n\n"
    "export const isInkedName = (name: string): name is InkedName => name in NAMES\n\n"
    "// One icon at `size` px, filled with `color` (the theme's own), optionally\n"
    "// turned by `turn` degrees about its centre (the rolling d20).\n"
    "export function inkedSvg(name: InkedName, size: number, color: string, turn = 0): string {\n"
    "  const rotate = turn === 0 ? '' : ` transform=\"rotate(${turn} 256 256)\"`\n"
    "  return `<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 512 512\" width=\"${size}\" height=\"${size}\"><path fill=\"${color}\"${rotate} d=\"${PATHS[NAMES[name]] ?? ''}\"/></svg>`\n"
    "}\n"
)
OUT.write_text(ts)
print(OUT, len(ts), 'bytes', len(names), 'names', len(data), 'paths')
