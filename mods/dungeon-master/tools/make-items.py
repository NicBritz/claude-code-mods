# Generates items.ts: cropped SVG path markup for 0x72 item sprites.
# Usage: python3 -I make-items.py [frames dir] [out .ts]
# Pure stdlib (own PNG decoder, same approach as agent-pals' png2svg.py).
import sys, zlib, struct, json, pathlib

HERE = pathlib.Path(__file__).resolve().parent
# Pass the unpacked pack's frames folder as the first argument.
DEFAULT_FRAMES = None

ITEMS = {
    'chest': 'chest_full_open_anim_f2',
    'hammer': 'weapon_hammer',
    'staff': 'weapon_red_magic_staff',
    'bow': 'weapon_bow',
    'arrow': 'weapon_arrow',
    'sword': 'weapon_knight_sword',
    'coin': 'coin_anim_f0',
    'flask': 'flask_big_green',
    'skull': 'skull',
    'heart': 'ui_heart_empty',
    'banner': 'wall_banner_red',
}

def decode(path):
    data = pathlib.Path(path).read_bytes()
    assert data[:8] == b'\x89PNG\r\n\x1a\n'
    pos, idat, w, h = 8, b'', 0, 0
    while pos < len(data):
        length, kind = struct.unpack('>I4s', data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        if kind == b'IHDR':
            w, h, depth, ctype, _, _, interlace = struct.unpack('>IIBBBBB', body)
            assert depth == 8 and ctype == 6 and interlace == 0, path
        elif kind == b'IDAT':
            idat += body
        pos += 12 + length
    raw, stride, rows, prev = zlib.decompress(idat), w * 4, [], bytearray(w * 4)
    for y in range(h):
        f, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - 4] if i >= 4 else 0
            b = prev[i]
            c = prev[i - 4] if i >= 4 else 0
            if f == 1: line[i] = (line[i] + a) & 255
            elif f == 2: line[i] = (line[i] + b) & 255
            elif f == 3: line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c; pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(line); prev = line
    return w, h, [[tuple(r[x * 4:x * 4 + 4]) for x in range(w)] for r in rows]

def markup(path):
    """Returns (width, height, paths) for the cropped bounding box of visible pixels."""
    w, h, px = decode(path)
    # Skip nearly transparent pixels (alpha < 0.1).
    vis = [[px[y][x][3] >= 26 for x in range(w)] for y in range(h)]
    xs = [x for y in range(h) for x in range(w) if vis[y][x]]
    ys = [y for y in range(h) for x in range(w) if vis[y][x]]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    paths = {}
    for y in range(y0, y1 + 1):
        x = x0
        while x <= x1:
            if not vis[y][x]: x += 1; continue
            col = px[y][x]
            run = 1
            while x + run <= x1 and vis[y][x + run] and px[y][x + run] == col: run += 1
            paths.setdefault(col, []).append(f'M{x - x0} {y - y0}h{run}v1h-{run}z')
            x += run
    out = ''
    for (r, g, b, a), ds in paths.items():
        op = '' if a == 255 else f' fill-opacity="{a / 255:.2f}"'
        out += f'<path fill="#{r:02x}{g:02x}{b:02x}"{op} d="{"".join(ds)}"/>'
    return x1 - x0 + 1, y1 - y0 + 1, out

frames = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else sys.exit('usage: give the frames folder of 0x72 DungeonTileset II as the first argument')
out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else HERE.parent / 'hooks' / 'items.ts'

items = {}
for key, stem in ITEMS.items():
    w, h, paths = markup(frames / f'{stem}.png')
    items[key] = {'width': w, 'height': h, 'paths': paths}
    print(key, w, h, len(paths))

names = ' | '.join(f"'{k}'" for k in ITEMS)
body = ',\n'.join(
    f'  {json.dumps(k)}: {{ width: {v["width"]}, height: {v["height"]}, paths: {json.dumps(v["paths"])} }}'
    for k, v in items.items())
ts = ('// Generated from 0x72\'s "16x16 DungeonTileset II" (CC0, https://0x72.itch.io/dungeontileset-ii).\n'
      '// Item icons cropped to their pixels, as SVG path markup. Generated by make-items.py. Do not edit by hand.\n\n'
      f'export type ItemName = {names}\n\n'
      'export const ITEMS: Record<ItemName, { width: number; height: number; paths: string }> = {\n'
      f'{body},\n}}\n\n'
      '// The item centred in a square viewBox, so every icon scales the same way.\n'
      'export function itemSvg(name: ItemName, size = 16): string {\n'
      '  const { width, height, paths } = ITEMS[name]\n'
      '  const s = Math.max(width, height)\n'
      '  const dx = (s - width) / 2\n'
      '  const dy = (s - height) / 2\n'
      '  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${-dx} ${-dy} ${s} ${s}" width="${size}" height="${size}" shape-rendering="crispEdges">${paths}</svg>`\n'
      '}\n')
out.write_text(ts)
print(out, len(ts), 'chars')
